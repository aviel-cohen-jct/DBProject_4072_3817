-- ====================================================================
-- שלב ד: שינויי סכמה (Alter Table)
-- מגישים: אביאל כהן, נתנאל דהן
-- ====================================================================
-- מטרה: להעשיר את טבלת USERS בשתי עמודות שיתמכו בלוגיקת התכנות של
-- שלב ד - חישוב תשואת סגל (Portfolio_Yield) ביחס לתקציב ההתחלתי
-- הקבוע של המשתמש (Initial_Budget), שאינו משתנה עם המסחר.
-- ====================================================================

-- Initial_Budget: התקציב שאיתו התחיל המשתמש (קבוע, לא מתעדכן במסחר).
-- ברירת המחדל 100000 חלה גם על המשתמשים הקיימים (500 רשומות משלב א).
ALTER TABLE USERS ADD COLUMN Initial_Budget INT NOT NULL DEFAULT 100000;

-- Portfolio_Yield: אחוז התשואה הנוכחי של הסגל ((שווי כולל - תקציב התחלתי) / תקציב התחלתי * 100).
-- מחושב ומתעדכן ע"י הפונקציה fn_calculate_portfolio_value (Functions.sql).
ALTER TABLE USERS ADD COLUMN Portfolio_Yield NUMERIC(8,2);
